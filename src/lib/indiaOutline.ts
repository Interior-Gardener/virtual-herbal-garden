/* ------------------------------------------------------------------ *
 * India's boundary, in longitude/latitude.
 *
 * Traced from the Survey of India-derived composite published by
 * DataMeet (public domain), simplified to ~11 km of detail. It carries
 * the boundary as India officially claims it — Jammu & Kashmir, Ladakh
 * and Arunachal Pradesh included — which is what any map published from
 * India has to show.
 *
 * The coordinates stay geographic and are projected at import, so the
 * region markers can be given as real places rather than pixels.
 * ------------------------------------------------------------------ */

/** Extent of the drawn territory, mainland and islands together. */
export const INDIA_EXTENT = { west: 68.17, east: 97.4, south: 6.75, north: 37.1 }

/** Equirectangular, true to scale along 23.5°N — the tropic runs through India. */
const PARALLEL = Math.cos((23.5 * Math.PI) / 180)

const MARGIN = 12
const VIEW = { width: 420, height: 480 }
const SPAN_X = (INDIA_EXTENT.east - INDIA_EXTENT.west) * PARALLEL
const SPAN_Y = INDIA_EXTENT.north - INDIA_EXTENT.south
const SCALE = Math.min((VIEW.width - MARGIN * 2) / SPAN_X, (VIEW.height - MARGIN * 2) / SPAN_Y)
const OFFSET_X = (VIEW.width - SPAN_X * SCALE) / 2
const OFFSET_Y = (VIEW.height - SPAN_Y * SCALE) / 2

export const INDIA_VIEWBOX = `0 0 ${VIEW.width} ${VIEW.height}`

/** Longitude/latitude to a point in the map's viewBox. */
export function project(lon: number, lat: number): [number, number] {
  return [
    (lon - INDIA_EXTENT.west) * PARALLEL * SCALE + OFFSET_X,
    (INDIA_EXTENT.north - lat) * SCALE + OFFSET_Y,
  ]
}

/** An SVG path for a ring of longitude/latitude pairs. */
export function pathFor(ring: [number, number][]): string {
  return (
    ring
      .map(([lon, lat], i) => {
        const [x, y] = project(lon, lat)
        return `${i === 0 ? 'M' : 'L'} ${x.toFixed(1)} ${y.toFixed(1)}`
      })
      .join(' ') + ' Z'
  )
}

